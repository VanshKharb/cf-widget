#!/bin/bash
# One-time setup: writes Config/Identity.xcconfig, then generates the Xcode project.
#
#   ./Tools/setup.sh                  # asks for your Team ID and bundle prefix
#   ./Tools/setup.sh ABCDE12345 com.yourname
set -euo pipefail

cd "$(dirname "$0")/.."

TEAM="${1:-}"
PREFIX="${2:-}"

if [[ -z "$TEAM" ]]; then
  echo "Find your Team ID in Xcode > Settings > Accounts (10 characters, e.g. ABCDE12345)."
  read -r -p "Team ID: " TEAM
fi

if [[ -z "$PREFIX" ]]; then
  echo
  echo "Choose a reverse-DNS prefix that is unique to you, e.g. com.yourname."
  echo "It becomes your bundle ID and App Group ID, so it cannot clash with anyone else's."
  read -r -p "Bundle prefix: " PREFIX
fi

TEAM="$(printf '%s' "$TEAM" | tr -d '[:space:]')"
PREFIX="$(printf '%s' "$PREFIX" | tr -d '[:space:]')"
PREFIX="${PREFIX%.}"

if [[ ${#TEAM} -ne 10 ]]; then
  echo "error: a Team ID is 10 characters, got '${TEAM}'." >&2
  exit 1
fi

if [[ ! "$PREFIX" =~ ^[A-Za-z0-9.-]+$ ]]; then
  echo "error: bundle prefix must look like com.yourname." >&2
  exit 1
fi

mkdir -p Config
cat > Config/Identity.xcconfig <<EOF
// Generated by Tools/setup.sh — gitignored, safe to edit.
DEVELOPMENT_TEAM = ${TEAM}
BUNDLE_PREFIX = ${PREFIX}
APP_GROUP = group.${PREFIX}.cfwidget
EOF

echo
echo "Wrote Config/Identity.xcconfig:"
sed 's/^/  /' Config/Identity.xcconfig

echo
if ! command -v xcodegen >/dev/null 2>&1; then
  echo "xcodegen is missing. Install it, then generate the project:"
  echo "  brew install xcodegen && xcodegen generate"
  exit 0
fi

xcodegen generate
echo
echo "Done. Open CFWidget.xcodeproj, pick your iPhone, and press ⌘R."
